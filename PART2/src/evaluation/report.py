"""Generate docs/RESULTS.md from the evaluation CSVs so no number is ever typed by hand."""
from __future__ import annotations
from datetime import date
import numpy as np
import pandas as pd
from src.config import ROOT


INT_COLS = {"efficacy_rank", "n_parameters", "epochs_trained", "simplicity_loc", "simplicity_rating",
            "transparency_rating", "TN", "FP", "FN", "TP"}


def _md(df: pd.DataFrame, floats: int = 4) -> str:
    if df.empty:
        return "_none_\n"
    d = df.copy()
    for c in d.columns:
        if c in INT_COLS and pd.api.types.is_numeric_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else str(int(v)))
        elif pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.{floats}f}")
    d = d.fillna("").astype(str)
    head = "| " + " | ".join(d.columns) + " |\n|" + "|".join("---" for _ in d.columns) + "|\n"
    return head + "\n".join("| " + " | ".join(r) + " |" for r in d.values) + "\n"


def write_results_doc(res: dict, tag: str = "main") -> None:
    d = res["dirs"]["results"]
    cmp, rt, ct = res["comparison"], res["regression_test_metrics"], res["classification_test_metrics"]
    b = res["bundle"]; n = len(b.y_test_reg)
    hw = 1.96 * np.sqrt(0.25 / n) * 100
    fw = cmp[~cmp.framework.eq("baseline")]
    evaluated_fw = fw[fw.status == "evaluated"]
    lines = [f"# Results (auto-generated by `run_evaluation.py`, {date.today().isoformat()}, run tag `{tag}`)\n"]
    lines.append(f"**Framework models with real results: {len(evaluated_fw)} of {len(fw)}.** "
                 f"Baselines evaluated: {int((cmp[cmp.framework.eq('baseline')].status == 'evaluated').sum())} of "
                 f"{int(cmp.framework.eq('baseline').sum())}.\n")
    if len(evaluated_fw) < len(fw):
        lines.append("> **Not every framework model has been trained in this results set.** Rows without results are listed "
                     "in the section 'Models without results' with the exact error. Nothing was estimated or filled in. "
                     "Run `python run_models.py && python run_evaluation.py` in an environment where `requirements.txt` "
                     "is installed to populate them; this file regenerates automatically.\n")
    if len(set(evaluated_fw.implementation)) and (evaluated_fw.implementation != "native").any():
        odd = evaluated_fw[evaluated_fw.implementation != "native"][["model", "implementation"]]
        lines.append("> Some rows were NOT produced by the framework they are named after (see `implementation`):\n\n" + _md(odd))

    lines.append(f"\n## Test-set regression (`target_next_day_return`, n = {n})\n")
    lines.append(_md(rt[["model", "MAE", "RMSE", "R2", "Directional_Accuracy"]], 5))
    lines.append(f"\n## Test-set classification (`target_next_day_up`, n = {n}; share of up days = {b.y_test_clf.mean():.3f})\n")
    lines.append(_md(ct[["model", "Accuracy", "Precision", "Recall", "F1", "ROC_AUC", "TN", "FP", "FN", "TP"]]))

    lines.append("\n## How much of this difference is signal?\n")
    lines.append(f"With n = {n} test days, an accuracy or directional accuracy is only known to about ±{hw:.1f} percentage points "
                 "(95%, binomial). Differences smaller than that are indistinguishable from noise. ")
    if len(evaluated_fw) == 0:
        lines.append("**No framework model has results yet, so no comparison against the baselines is possible.** "
                     "Only the baselines above are real results.")
    if len(evaluated_fw) and not ct.empty:
        maj = ct.loc[ct.model == "baseline_majority_class_clf", "Accuracy"]
        if len(maj):
            ct2 = ct.assign(lift_pp=(ct.Accuracy - maj.iloc[0]) * 100)
            clear = ct2[(ct2.lift_pp > ct2.Accuracy_CI95_halfwidth * 100) & (~ct2.model.str.startswith("baseline"))]
            lines.append("**Classification:** " + (f"{', '.join(clear.model)} beat the always-up baseline by more than the 95% margin."
                         if len(clear) else "no evaluated framework model beats the always-up baseline by more than the 95% margin.") + " ")
    if len(evaluated_fw) and not rt.empty:
        mean_rmse = rt.loc[rt.model == "baseline_train_mean_reg", "RMSE"]
        if len(mean_rmse):
            better = rt[(rt.RMSE < mean_rmse.iloc[0]) & (~rt.model.str.startswith("baseline"))]
            lines.append("**Regression:** " + (f"{', '.join(better.model)} achieve a lower RMSE than predicting the training mean."
                         if len(better) else "no evaluated framework model achieves a lower RMSE than predicting the training mean."))
    lines.append("\n\nThe expected outcome for next-day index returns from price-derived features is small or no out-of-sample "
                 "skill, so a result close to the baselines is a legitimate finding, not a failure of the pipeline.\n")

    lines.append("\n## Model comparison on the five criteria\n")
    lines.append("*Efficacy* and *prediction performance* are measured (test metrics, rank among evaluated models of the same task, baselines included; 1 = best). "
                 "*Training time* is measured wall-clock on the machine that ran `run_models.py`. *Simplicity* is shown as lines of "
                 "code in the model module (objective proxy) plus an analyst rating; *transparency* is an analyst rating "
                 "(1 = poor, 5 = excellent) - see docs/METHODOLOGY_PART2.md for the rubric.\n\n")
    cols = ["model", "status", "implementation", "efficacy_rank", "train_time_sec", "n_parameters", "epochs_trained",
            "simplicity_loc", "simplicity_rating", "transparency_rating"]
    lines.append(_md(cmp[cols], 3))

    bad = cmp[~cmp.status.isin(["evaluated"])][["model", "status", "error"]]
    lines.append("\n## Models without results\n")
    lines.append(_md(bad))

    lines.append("\n## Figures (`outputs/model_graphs/`)\n")
    lines.append("`regression_comparison.png`, `classification_comparison.png`, `roc_curves.png`, `confusion_matrices.png`, "
                 "`regression_pred_vs_actual.png`, `training_time.png`, `feature_importance_<model>.png` "
                 "(+ `training_curve_<model>.png` for Keras).\n")
    abl = ROOT / "outputs" / "results" / "feature_set_ablation_validation.csv"
    if abl.exists():
        lines.append("\n## Feature-set ablation (train -> validation only)\n")
        lines.append("Part 1 delivered 21 predictors including raw `open/high/low/close`. 93% of validation rows have a `close` above "
                     "the training maximum, so price levels are out of range. The default modelling set drops them (17 features). "
                     "On validation this ablation is **inconclusive** (differences are small and mixed), so the choice rests on "
                     "the non-stationarity argument, not on a demonstrated accuracy gain.\n\n")
        lines.append(_md(pd.read_csv(abl)))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")


def publish_deliverables(res: dict) -> None:
    """Copy the final tables and figures of the real (main) run into the shared deliverables folders."""
    import shutil
    for src, dst in [(res["dirs"]["results"], ROOT / "deliverables" / "model_results"),
                     (res["dirs"]["graphs"], ROOT / "deliverables" / "graphs" / "part2")]:
        dst.mkdir(parents=True, exist_ok=True)
        shutil.copytree(src, dst, dirs_exist_ok=True)
